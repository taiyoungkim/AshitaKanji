#!/usr/bin/env node
// assets/audio/{words,examples}/<id>.{mp3,ogg} → platform audio maps
// Android는 Ogg/Opus, iOS/web은 MP3를 사용한다. 활성 DB word.id만 정적
// 맵에 넣어 Metro가 최종 릴리즈 자산만 번들하게 한다.
//
// 실행: node scripts/gen-audio-map.mjs
// 선행: scripts/gen-tts-audio.py 로 mp3 생성 완료

import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BASE = resolve(ROOT, 'assets/audio');
const OUT_DEFAULT = resolve(ROOT, 'src/lib/audio/audioMap.gen.ts');
const OUT_ANDROID = resolve(ROOT, 'src/lib/audio/audioMap.gen.android.ts');
const DB = resolve(ROOT, 'assets/jlpt.db');
const includeOrphans = process.argv.includes('--include-orphans');

function activeWordIds() {
  if (includeOrphans) return null;
  if (!existsSync(DB)) throw new Error(`Active vocabulary DB not found: ${DB}`);
  const output = execFileSync('sqlite3', [DB, 'SELECT id FROM word WHERE deprecated=0;'], {
    encoding: 'utf8',
  });
  return new Set(output.split('\n').map((id) => id.trim()).filter(Boolean));
}

const activeIds = activeWordIds();

function entries(kindDir, extension) {
  const dir = resolve(BASE, kindDir);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(`.${extension}`))
    .filter((f) => activeIds == null || activeIds.has(f.slice(0, -(extension.length + 1))))
    .map((f) => {
      const id = f.slice(0, -(extension.length + 1));
      return `  ${JSON.stringify(id)}: require('../../../assets/audio/${kindDir}/${f}'),`;
    });
}

function generate(output, extension, platform) {
  const words = entries('words', extension);
  const examples = entries('examples', extension);
  const lintDirective = platform === 'Android'
    ? '/* eslint-disable @typescript-eslint/no-require-imports */\n'
    : '';
  const out = `// AUTO-GENERATED by scripts/gen-audio-map.mjs — do not edit by hand.
// ${platform}: id -> bundled ${extension} asset module. Used by src/lib/audio/wordAudio.ts.
${lintDirective}export const WORD_AUDIO: Record<string, number> = {
${words.join('\n')}
};
export const EXAMPLE_AUDIO: Record<string, number> = {
${examples.join('\n')}
};
`;
  writeFileSync(output, out);
  console.log(
    `generated ${output}: format=${extension} words=${words.length} examples=${examples.length} ` +
      `scope=${includeOrphans ? 'all-files' : 'active-db-only'}`,
  );
}

generate(OUT_DEFAULT, 'mp3', 'iOS/web/default');
generate(OUT_ANDROID, 'ogg', 'Android');
