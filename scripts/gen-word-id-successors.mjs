#!/usr/bin/env node
// Build src/db/wordIdSuccessors.gen.ts from the frequency-core correction list.
// Only same-word spelling/orthography fixes (identity_changed).
// Kana→kanji merges, wrong-reading merges, inflection/phrase collapses, and
// "retire this word, add a different PDF-core word" swaps are omitted.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const finalManifest = JSON.parse(
  readFileSync(resolve(root, 'data/pdf-vocab/jlpt_final_replacement_manifest.json'), 'utf8'),
);

const successors = {};
for (const row of finalManifest.retained_corrections ?? []) {
  if (!row.identity_changed) continue;
  const from = row.old_id;
  const to = row.new_id;
  if (!from || !to || from === to) continue;
  successors[from] = to;
}

const extraManifests = [
  'data/pdf-vocab/jlpt_na_adjective_dedupe_manifest.json',
  'data/pdf-vocab/jlpt_priority_fix_manifest.json',
  'data/pdf-vocab/jlpt_remaining_review_manifest.json',
  'data/pdf-vocab/jlpt_feedback_fix_manifest.json',
  'data/pdf-vocab/jlpt_spelling_queue_manifest.json',
  'data/pdf-vocab/jlpt_naver_crosscheck_fix_manifest.json',
  'data/pdf-vocab/jlpt_mada_imada_split_manifest.json',
  'data/pdf-vocab/jlpt_shikatanai_n4_manifest.json',
  'data/pdf-vocab/jlpt_orthography_variant_manifest.json',
];
function setSuccessor(from, to) {
  if (!from || !to || from === to) return;
  successors[from] = to;
  if (successors[to] === from) delete successors[to];
}

for (const relative of extraManifests) {
  try {
    const extra = JSON.parse(readFileSync(resolve(root, relative), 'utf8'));
    for (const [from, to] of Object.entries(extra.successors ?? {})) {
      setSuccessor(from, to);
    }
  } catch {
    // Optional later-pass manifests.
  }
}

function resolveSuccessor(start) {
  const seen = new Set();
  let current = start;
  while (successors[current] && !seen.has(current)) {
    seen.add(current);
    current = successors[current];
  }
  return current;
}

for (const from of Object.keys(successors)) {
  const terminal = resolveSuccessor(from);
  if (!terminal || terminal === from) {
    delete successors[from];
  } else {
    successors[from] = terminal;
  }
}

const sorted = Object.fromEntries(Object.entries(successors).sort(([a], [b]) => a.localeCompare(b)));
const outPath = resolve(root, 'src/db/wordIdSuccessors.gen.ts');
const body = `// Generated by scripts/gen-word-id-successors.mjs. Do not edit by hand.
// Same-word spelling fixes only (identity_changed). Old word.id → surviving word.id.

export const WORD_ID_SUCCESSORS: Readonly<Record<string, string>> = ${JSON.stringify(sorted, null, 2)};
`;
writeFileSync(outPath, `${body}\n`);
console.log(`wrote ${Object.keys(sorted).length} successors → ${outPath}`);
